/**
 * Custom Cloudflare Worker entry (wrangler.jsonc → "main").
 *
 * OpenNext builds the Next.js app into .open-next/worker.js, which only handles HTTP.
 * This file re-uses its fetch handler unchanged and adds a `scheduled` handler for
 * the cron trigger in wrangler.jsonc (every 5 minutes):
 *   • cancel waitlist holds nobody confirmed in time
 *   • give each freed seat to the next person in the queue
 *
 * Build/deploy is unchanged: `npm run cf:deploy` builds .open-next first, then wrangler
 * bundles this file. Test the cron locally with `npm run cf:preview -- --test-scheduled`
 * and open http://localhost:8787/__scheduled.
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — generated by `opennextjs-cloudflare build`, so it doesn't exist before the first build.
import { default as handler } from "./.open-next/worker.js";
import { sweepHolds } from "./src/lib/data/registrations";

export default {
  fetch: handler.fetch,

  async scheduled(controller, env, ctx) {
    ctx.waitUntil(
      sweepHolds(env.DB, new Date(controller.scheduledTime)).then((r) =>
        console.log(`[cron ${controller.cron}] holds expired: ${r.expired}, seats offered: ${r.promoted}`),
      ),
    );
  },
} satisfies ExportedHandler<CloudflareEnv>;
