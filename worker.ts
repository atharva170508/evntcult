/**
 * Custom Cloudflare Worker entry (wrangler.jsonc → "main").
 *
 * OpenNext builds the Next.js app into .open-next/worker.js, which handles normal HTTP.
 * This file wraps it and adds what Next.js route handlers can't do:
 *
 *  • fetch: GET /api/events/:id/live (WebSocket) → the event's EventLive Durable Object,
 *    after checking the viewer organizes that event. Everything else goes to Next.js.
 *  • scheduled: the cron in wrangler.jsonc (every 5 minutes) expires unconfirmed
 *    waitlist holds, gives freed seats to the next person, and queues the WhatsApp
 *    reminder for events starting within 24 hours (once per student).
 *  • exports the EventLive Durable Object class.
 *
 * Build/deploy is unchanged: `npm run cf:deploy`. To try the cron and WebSockets locally:
 * `npm run cf:preview -- --test-scheduled`, then open http://localhost:8787/__scheduled.
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — generated by `opennextjs-cloudflare build`, so it doesn't exist before the first build.
import { default as handler } from "./.open-next/worker.js";
import { sweepHolds } from "./src/lib/data/registrations";
import { purgeOldCodes } from "./src/lib/data/login-codes";
import { purgeFaceSearchLog } from "./src/lib/data/face-search";
import { gateCounts } from "./src/lib/data/checkins";
import { queueDayBeforeReminders } from "./src/lib/notify";
import { readSessionValue, SESSION_COOKIE } from "./src/lib/session";

export { EventLive } from "./src/lib/live/event-live";

const LIVE_PATH = /^\/api\/events\/([^/]+)\/live$/;

function cookie(req: Request, name: string): string | null {
  const header = req.headers.get("Cookie") ?? "";
  for (const part of header.split(";")) {
    const [k, ...v] = part.trim().split("=");
    if (k === name) return v.join("=");
  }
  return null;
}

/** May this viewer watch this event's gate count? (organizer of the event, or admin) */
async function canWatch(env: CloudflareEnv, req: Request, eventId: string): Promise<boolean> {
  const uid = await readSessionValue(cookie(req, SESSION_COOKIE));
  if (!uid) return false;
  const row = await env.DB.prepare(
    "SELECT u.role, e.organizer_id FROM users u, events e WHERE u.id = ? AND e.id = ?",
  )
    .bind(uid, eventId)
    .first<{ role: string; organizer_id: string }>();
  return !!row && (row.role === "admin" || (row.role === "organizer" && row.organizer_id === uid));
}

async function liveSocket(req: Request, env: CloudflareEnv, eventId: string): Promise<Response> {
  if (req.headers.get("Upgrade") !== "websocket") return new Response("Expected a WebSocket", { status: 426 });
  if (!env.EVENT_LIVE) return new Response("Live updates aren't available here", { status: 503 });
  if (!(await canWatch(env, req, eventId))) return new Response("Forbidden", { status: 403 });

  const counts = { ...(await gateCounts(env.DB, eventId)), at: Date.now() };
  const stub = env.EVENT_LIVE.get(env.EVENT_LIVE.idFromName(eventId));
  const forwarded = new Request(req.url, { headers: { Upgrade: "websocket", "x-gate-counts": JSON.stringify(counts) } });
  return stub.fetch(forwarded);
}

export default {
  async fetch(req, env, ctx) {
    const match = new URL(req.url).pathname.match(LIVE_PATH);
    if (match && req.method === "GET") return liveSocket(req, env, decodeURIComponent(match[1]));
    return handler.fetch(req, env, ctx);
  },

  async scheduled(controller, env, ctx) {
    const now = new Date(controller.scheduledTime);
    ctx.waitUntil(
      (async () => {
        const holds = await sweepHolds(env.DB, now);
        const reminders = await queueDayBeforeReminders(env.DB, now);
        await purgeOldCodes(env.DB, now);
        await purgeFaceSearchLog(env.DB, now);
        console.log(`[cron ${controller.cron}] holds expired: ${holds.expired}, seats offered: ${holds.promoted}, reminders queued: ${reminders}`);
      })(),
    );
  },
} satisfies ExportedHandler<CloudflareEnv>;
